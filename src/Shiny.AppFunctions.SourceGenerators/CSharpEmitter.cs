            sb.AppendLine("                }");
        }
        sb.AppendLine("            }");
        sb.AppendLine($"            throw new {R}AppFunctionException({R}AppFunctionErrorCode.NotFound, \"Unknown entity '\" + entityId + \"'\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    static string ReadArgument(ParameterModel p)
    {
        var args = $"args, {Str(p.WireName)}, {Bool(p.IsRequired)}";
        var bang = p.IsRequired ? (p.Type.IsValueType ? "!.Value" : "!") : "";
        return p.Type.Kind switch
        {
            ValueKind.String => $"{R}AppFunctionArguments.GetString({args}){bang}",
            ValueKind.Int32 => $"{R}AppFunctionArguments.GetInt32({args}){bang}",
            ValueKind.Int64 => $"{R}AppFunctionArguments.GetInt64({args}){bang}",
            ValueKind.Double => $"{R}AppFunctionArguments.GetDouble({args}){bang}",
            ValueKind.Boolean => $"{R}AppFunctionArguments.GetBoolean({args}){bang}",
            ValueKind.DateTimeOffset => $"{R}AppFunctionArguments.GetDateTimeOffset({args}){bang}",
            ValueKind.Enum => $"{R}AppFunctionArguments.GetEnum<{p.Type.CSharpBaseType}>({args}){bang}",
            ValueKind.Entity => $"(await {R}AppFunctionArguments.GetEntity<{p.Type.CSharpBaseType}>({args}, services, cancellationToken).ConfigureAwait(false)){bang}",
            _ => "default!"
        };
    }

    /// <summary>Writes <paramref name="expr"/> as JSON, null-checking anything that can be null.</summary>
    static void EmitWrite(StringBuilder sb, TypeModel type, string expr, string indent, ref int counter)
    {
        var mayBeNull = !type.IsValueType || type.IsNullable;
        var v = expr;
        if (mayBeNull)
        {
            var name = "v" + counter++;
            sb.AppendLine($"{indent}if ({expr} is not {{ }} {name}) writer.WriteNullValue();");
            sb.AppendLine($"{indent}else");
            sb.AppendLine($"{indent}{{");
            v = name;
            indent += "    ";
        }

        switch (type.Kind)
        {
            case ValueKind.String:
                sb.AppendLine($"{indent}writer.WriteStringValue({v});");
                break;
            case ValueKind.Int32:
            case ValueKind.Int64:
            case ValueKind.Double:
                sb.AppendLine($"{indent}writer.WriteNumberValue({v});");
                break;
            case ValueKind.Boolean:
                sb.AppendLine($"{indent}writer.WriteBooleanValue({v});");
                break;
            case ValueKind.DateTimeOffset:
                sb.AppendLine($"{indent}{R}AppFunctionArguments.WriteDateTimeOffset(writer, {v});");
                break;
            case ValueKind.Enum:
                sb.AppendLine($"{indent}writer.WriteStringValue({v}.ToString());");
                break;
            case ValueKind.Object:
                sb.AppendLine($"{indent}writer.WriteStartObject();");
                foreach (var p in type.Properties)
                {
                    sb.AppendLine($"{indent}writer.WritePropertyName({Str(p.WireName)});");
                    EmitWrite(sb, p.Type, $"{v}.{p.CSharpName}", indent, ref counter);
                }
                sb.AppendLine($"{indent}writer.WriteEndObject();");
                break;
            case ValueKind.Array:
                var item = "item" + counter++;
                sb.AppendLine($"{indent}writer.WriteStartArray();");
                sb.AppendLine($"{indent}foreach (var {item} in {v})");
                sb.AppendLine($"{indent}{{");
                EmitWrite(sb, type.ItemType!, item, indent + "    ", ref counter);
                sb.AppendLine($"{indent}}}");
                sb.AppendLine($"{indent}writer.WriteEndArray();");
                break;
        }

        if (mayBeNull)
            sb.AppendLine($"{indent.Substring(4)}}}");
    }

    static string TypeDescriptor(TypeModel t)
    {
        var parts = new List<string>
        {
            $"Kind = {R}AppValueKind.{t.Kind}",
            $"IsNullable = {Bool(t.IsNullable)}"
        };
        if (t.TypeName.Length > 0)
            parts.Add($"TypeName = {Str(t.TypeName)}");
        if (t.EntityId != null)
            parts.Add($"EntityId = {Str(t.EntityId)}");
        if (t.EnumValues.Count > 0)
            parts.Add($"EnumValues = new string[] {{ {string.Join(", ", t.EnumValues.Select(Str))} }}");
        if (t.Properties.Count > 0)
            parts.Add($"Properties = new {R}AppPropertyDescriptor[] {{ {string.Join(", ", t.Properties.Select(p => $"new {R}AppPropertyDescriptor {{ Name = {Str(p.WireName)}, Type = {TypeDescriptor(p.Type)} }}"))} }}");
        if (t.ItemType != null)
            parts.Add($"ItemType = {TypeDescriptor(t.ItemType)}");
        return $"new {R}AppTypeDescriptor {{ {string.Join(", ", parts)} }}";
    }

    static string Bool(bool value) => value ? "true" : "false";

    public static string Str(string? value)
    {
        if (value == null)
            return "null";
        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ')
                        sb.Append("\\u").Append(((int)c).ToString("x4"));
                    else
                        sb.Append(c);
                    break;
            }
        }
        return sb.Append('"').ToString();
    }

    static string Verbatim(string value) => "@\"" + value.Replace("\"", "\"\"") + "\"";
}
