        sb.AppendLine("        {");
        sb.AppendLine("            switch (entityId)");
        sb.AppendLine("            {");
        foreach (var e in model.Entities)
        {
            sb.AppendLine($"                case {Str(e.Id)}:");
            sb.AppendLine("                {");
            sb.AppendLine($"                    var query = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{R}IAppEntityQuery<{e.CSharpType}>>(services);");
            sb.AppendLine("                    var found = kind switch");
            sb.AppendLine("                    {");
            sb.AppendLine($"                        {R}AppEntityQueryKind.ByIds => await query.GetByIds(arguments, cancellationToken).ConfigureAwait(false),");
