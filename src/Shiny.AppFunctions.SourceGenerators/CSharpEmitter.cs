    static void EmitRegistration(StringBuilder sb, GenerationModel model)
    {
        sb.AppendLine("namespace Microsoft.Extensions.DependencyInjection");
        sb.AppendLine("{");
        sb.AppendLine("    internal static class ShinyAppFunctionsRegistration");
        sb.AppendLine("    {");
        sb.AppendLine("        /// <summary>Registers every app function handler, entity query and delegate in this project, plus the Shiny.AppFunctions runtime.</summary>");
        sb.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddAppFunctions(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("        {");
        foreach (var fn in model.Functions.Where(f => f.HandlerType != null && f.SearchesEntityId == null))
            sb.AppendLine($"            services.AddScoped<{fn.HandlerInterface}, {fn.HandlerType}>();");
        foreach (var e in model.Entities.Where(e => e.QueryType != null))
            sb.AppendLine($"            services.AddScoped<{R}IAppEntityQuery<{e.CSharpType}>, {e.QueryType}>();");
        foreach (var d in model.Delegates)
            sb.AppendLine($"            global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(services, global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Scoped<{R}IAppFunctionDelegate, {d}>());");
        sb.AppendLine($"            {R}AppFunctionsServiceCollectionExtensions.AddAppFunctionsRuntime<global::Shiny.AppFunctions.Generated.GeneratedAppFunctionRegistry>(services);");
        sb.AppendLine("            return services;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    static void EmitRegistry(StringBuilder sb, GenerationModel model)
    {
        var declared = model.Functions.Where(f => f.SearchesEntityId == null).ToList();

        sb.AppendLine($"    internal sealed class GeneratedAppFunctionRegistry : {R}IAppFunctionRegistry");
        sb.AppendLine("    {");
        sb.AppendLine($"        static readonly {R}AppFunctionDescriptor[] functions = new {R}AppFunctionDescriptor[]");
        sb.AppendLine("        {");
        foreach (var fn in model.Functions)
        {
            sb.AppendLine($"            new {R}AppFunctionDescriptor");
            sb.AppendLine("            {");
            sb.AppendLine($"                Id = {Str(fn.Id)},");
            sb.AppendLine($"                Title = {Str(fn.Title)},");
            sb.AppendLine($"                Description = {Str(fn.Description)},");
            sb.AppendLine($"                OpensApp = {Bool(fn.OpensApp)},");
            if (fn.SearchesEntityId != null)
                sb.AppendLine($"                SearchesEntityId = {Str(fn.SearchesEntityId)},");
            sb.AppendLine($"                Parameters = new {R}AppParameterDescriptor[]");
            sb.AppendLine("                {");
            foreach (var p in fn.Parameters)
                sb.AppendLine($"                    new {R}AppParameterDescriptor {{ Name = {Str(p.WireName)}, Title = {Str(p.Title)}, Description = {Str(p.Description)}, IsRequired = {Bool(p.IsRequired)}, Type = {TypeDescriptor(p.Type)} }},");
            sb.AppendLine("                },");
            sb.AppendLine($"                Result = {TypeDescriptor(fn.Result)}");
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine($"        static readonly {R}AppEntityDescriptor[] entities = new {R}AppEntityDescriptor[]");
        sb.AppendLine("        {");
        foreach (var e in model.Entities)
            sb.AppendLine($"            new {R}AppEntityDescriptor {{ Id = {Str(e.Id)}, Title = {Str(e.Title)}, TypeName = {Str(e.TypeName)} }},");
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine($"        public global::System.Collections.Generic.IReadOnlyList<{R}AppFunctionDescriptor> Functions => functions;");
        sb.AppendLine($"        public global::System.Collections.Generic.IReadOnlyList<{R}AppEntityDescriptor> Entities => entities;");
        sb.AppendLine();

        // CreateRequest
        sb.AppendLine("        public async global::System.Threading.Tasks.ValueTask<object> CreateRequest(string functionId, global::System.Text.Json.JsonElement args, global::System.IServiceProvider services, global::System.Threading.CancellationToken cancellationToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (functionId)");
        sb.AppendLine("            {");
        foreach (var fn in declared)
        {
            sb.AppendLine($"                case {Str(fn.Id)}:");
            sb.AppendLine("                {");
            for (var i = 0; i < fn.Parameters.Count; i++)
                sb.AppendLine($"                    var p{i} = {ReadArgument(fn.Parameters[i])};");

            var ctorArgs = string.Join(", ", fn.Parameters.Select((p, i) => (p, i)).Where(x => x.p.ConstructorIndex >= 0).OrderBy(x => x.p.ConstructorIndex).Select(x => $"p{x.i}"));
            var initializers = fn.Parameters.Select((p, i) => (p, i)).Where(x => x.p.ConstructorIndex < 0).ToList();

            // an optional initializer property that was not sent keeps the value the type gives it
            var needsDefaults = initializers.Any(x => !x.p.IsRequired && !x.p.Type.IsNullable);
            if (needsDefaults)
                sb.AppendLine($"                    var defaults = new {fn.RequestType}({ctorArgs});");

            var inits = initializers.Select(x =>
                !x.p.IsRequired && !x.p.Type.IsNullable
                    ? $"{x.p.CSharpName} = p{x.i} ?? defaults.{x.p.CSharpName}"
                    : $"{x.p.CSharpName} = p{x.i}"
            ).ToList();
            var init = inits.Count == 0 ? "" : " { " + string.Join(", ", inits) + " }";
            sb.AppendLine($"                    return new {fn.RequestType}({ctorArgs}){init};");
            sb.AppendLine("                }");
        }
        sb.AppendLine("            }");
        sb.AppendLine($"            throw new {R}AppFunctionException({R}AppFunctionErrorCode.NotFound, \"Unknown function '\" + functionId + \"'\");");
        sb.AppendLine("        }");
        sb.AppendLine();

        // Invoke
        sb.AppendLine($"        public async global::System.Threading.Tasks.Task<object?> Invoke(object request, {R}AppFunctionContext context, global::System.Threading.CancellationToken cancellationToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (request)");
        sb.AppendLine("            {");
        for (var i = 0; i < declared.Count; i++)
        {
            var fn = declared[i];
            var resolve = $"global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{fn.HandlerInterface}>(context.Services)";
            sb.AppendLine($"                case {fn.RequestType} r{i}:");
            if (fn.Result.Kind == ValueKind.Void)
            {
                sb.AppendLine($"                    await {resolve}.Handle(r{i}, context, cancellationToken).ConfigureAwait(false);");
                sb.AppendLine("                    return null;");
            }
            else
            {
                sb.AppendLine($"                    return await {resolve}.Handle(r{i}, context, cancellationToken).ConfigureAwait(false);");
            }
        }
        sb.AppendLine("            }");
        sb.AppendLine("            throw new global::System.InvalidOperationException(\"No app function for \" + request.GetType().FullName);");
        sb.AppendLine("        }");
        sb.AppendLine();

        // WriteResult
        sb.AppendLine("        public void WriteResult(string functionId, object? result, global::System.Text.Json.Utf8JsonWriter writer)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (functionId)");
        sb.AppendLine("            {");
        var counter = 0;
        foreach (var fn in declared.Where(f => f.Result.Kind != ValueKind.Void))
